/* Core-app service regression tests. No teaching content or exercise library is seeded. */
const assert=require('node:assert/strict');
const Core=require('../dist/core-foundation.js');
const memory={};
const store={getItem:k=>memory[k]||null,setItem:(k,v)=>{memory[k]=v}};
const legacy={schema:3,names:['Jay','James'],lessons:{'0|11|scan':{seen:'2026-11-10'}},workouts:{}};
const a=Core.createRuntime(store,legacy);
const jay=a.playerIdForLegacyIndex(0),james=a.playerIdForLegacyIndex(1);
assert.deepEqual(a.profiles().map(p=>p.name),['Jay','James']);
assert.notEqual(jay,james);
a.setPositions(jay,['Winger','Striker','Fullback']);
a.setObjective(jay,{id:'decision',label:'Scan before receiving'});
assert.equal(a.getPlayer(jay).positions.length,3);
const s=a.createSession({playerId:jay,module:'lesson',contentId:'existing-scan',contentVersion:1});
assert.equal(s.status,'not_started');
a.transition(s.id,'in_progress');a.setCursor(s.id,2);a.transition(s.id,'paused');
assert.equal(a.resumable(jay).cursor,2);
const restored=Core.createRuntime(store,legacy);
assert.equal(restored.resumable(jay).cursor,2,'resume survives reload');
assert.equal(restored.resumable(james),null,'players are isolated');
restored.transition(s.id,'in_progress');
restored.transition(s.id,'completed');
restored.transition(s.id,'awaiting_match_application');
assert.equal(restored.sessionSummary(jay).awaitingMatch,1);
restored.recordEvent({playerId:jay,sessionId:s.id,type:'match_application',contentId:'existing-scan',details:{observed:true}});
restored.transition(s.id,'ready_for_review',{reviewDue:'2026-11-14'});
assert.equal(restored.recommend(jay,'2026-11-14',[]).kind,'review');
assert.equal(restored.sessionSummary(jay).independentlyVerified,0,'participation is not mastery');
assert.throws(()=>restored.recordEvent({playerId:jay,type:'competency_verified'}),/evidence/);
restored.recordEvent({playerId:jay,type:'competency_verified',assessment:{reviewerId:'coach-1',evidence:'Observed correct read in new situation'}});
assert.equal(restored.sessionSummary(jay).independentlyVerified,1);
const skip=restored.createSession({playerId:james,module:'drill',contentId:'legacy-track'});
restored.transition(skip.id,'skipped',{reason:'not feeling well'});
assert.equal(restored.sessionSummary(james).skipped,1);
assert.throws(()=>restored.transition(skip.id,'in_progress'),/Invalid/);
assert.equal(restored.recommend(james,'2026-11-12',[{id:'l-one',title:'Validated fixture'}]).kind,'new');
restored.setSchedule(james,[{kind:'practice',day:4}], [{kind:'match',date:'2026-11-14'}]);
assert.equal(restored.recommend(james,'2026-11-12',[]).kind,'scheduled');
assert.equal(restored.recommend(james,'2026-11-14',[]).kind,'scheduled');
restored.setSchedule(james,[],[{kind:'recovery',date:'2026-11-15'}]);
assert.equal(restored.recommend(james,'2026-11-15',[]).kind,'recovery');
const extra=restored.addPlayer('Third player');
assert.notEqual(extra,james);
assert.equal(restored.getPlayer(extra).name,'Third player');
const lesson={schemaVersion:1,id:'l1',title:'Test reference',media:[{assetId:'vid-1',kind:'video'}],prerequisites:[],positionTags:['Winger']};
const exercise={schemaVersion:1,id:'e1',title:'Test exercise',animation:{assetId:'anim-1',kind:'animation'}};
const workout={schemaVersion:1,id:'w1',items:[{exerciseId:'e1',sets:2,reps:'6 each'}]};
assert.ok(Core.validateLesson(lesson)&&Core.validateExercise(exercise)&&Core.validateWorkout(workout));
assert.ok(!Core.validateLesson({...lesson,media:[{kind:'video'}]}),'missing media ref rejected');
assert.ok(!Core.validateWorkout({...workout,items:[{exerciseId:'e1',sets:0}]}),'invalid set count rejected');
assert.equal(JSON.parse(memory[Core.storageKey]).schemaVersion,1);
assert.deepEqual(Core.createRuntime(store,legacy).profiles().slice(0,2).map(p=>p.id),[jay,james]);
console.log('PASS core foundation: profiles, isolated persistence, lifecycle, resume, skip, recovery, recommendations, competency evidence and integration contracts.');
